"""业务逻辑测试模板：把业务逻辑测试从「LLM 自主发挥」升级为「结构化可执行清单」。

背景：业务逻辑漏洞（越权/IDOR/状态机/并发/金额篡改）是差异化来源，但此前
business_profiler 只告诉 worker「测什么业务」、state_machine 只给「绕过手法」，
具体怎么一步步测仍靠 LLM 记忆发挥，容易漏测、测偏。

本模块为每个业务类型定义「测试模板」：一组可执行的测试点（TestPoint），
每个测试点含目标功能点、漏洞类型、具体测试步骤（含参数名/请求构造引导）、
实锤标准、无害性约束。Worker 拿到模板像 checklist 一样逐条实测。

- 纯规则确定性实现，可单测；不依赖 LLM。
- 通用模板（generic）兜底所有业务；业务专属模板按 biz_id 精确命中。
"""
from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class TestPoint:
    feature: str                # 目标功能点
    vuln_type: str              # 漏洞类型标签（idor/state_machine/concurrency/amount_tamper/auth_bypass/info_leak）
    steps: tuple[str, ...]      # 测试步骤（含参数名/请求构造引导）
    proof: str                  # 实锤标准（什么响应算命中）
    safe: str = ""              # 无害性约束


@dataclass(frozen=True)
class BizTestTemplate:
    biz_id: str
    label: str
    points: tuple[TestPoint, ...]


