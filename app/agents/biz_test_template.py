# ============ 选择与渲染 ============
def select_template(business_id: str) -> BizTestTemplate:
    """按业务类型选择模板；未识别业务返回通用模板。"""
    return _BUSINESS_TEMPLATES.get(business_id or "", _GENERIC_TEMPLATE)


def render_biz_test_block(
    business_id: str = "",
    business_label: str = "",
    max_points: int = 4,
) -> str:
    """渲染业务逻辑测试模板块，注入 Worker。无命中（通用模板）也返回通用清单。"""
    tmpl = select_template(business_id)
    label = business_label or tmpl.label
    lines = ["# 业务逻辑测试模板（按清单逐条实测，业务逻辑洞是差异化核心）"]
    lines.append(
        "不要只测单接口/只凭猜测。按下面清单逐条用 http_request 实测，"
        "每步命中实锤标准才算洞；没命中就换下一条。只做无害验证，禁止破坏真实数据。"
    )
    lines.append(f"[业务类型] {label}")
    for i, p in enumerate(tmpl.points[:max_points], 1):
        lines.append(f"{i}. [{p.vuln_type}] {p.feature}")
        lines.append("   步骤：")
        for s in p.steps:
            lines.append(f"   - {s}")
        lines.append(f"   实锤标准：{p.proof}")
        if p.safe:
            lines.append(f"   无害约束：{p.safe}")
    return "\n".join(lines) + "\n\n"
