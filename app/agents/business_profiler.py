def profile_business(
    *,
    url: str = "",
    title: str = "",
    org: str = "",
    school: str = "",
    priority_reason: str = "",
    src_type: str = "edusrc",
) -> BusinessProfile | None:
    """用编排层静态信息做初步业务识别，返回最高分业务画像；无命中返回 None。"""
    combined = "\n".join([url or "", title or "", org or "", school or "", priority_reason or ""])
    low = combined.lower()
    scored: list[tuple[float, _BizDef, list[str]]] = []
    for biz in _BUSINESS_PROFILES:
        hits = [kw for kw in biz.keywords if kw.lower() in low]
        if hits:
            score = min(3.0, len(hits) * biz.weight)
            scored.append((score, biz, hits))
    if not scored:
        return None
    scored.sort(key=lambda x: x[0], reverse=True)
    score, biz, hits = scored[0]
    if score < 1.0:
        return None
    confidence = min(0.95, 0.35 + score * 0.15)
    return BusinessProfile(
        biz_id=biz.biz_id,
        label=biz.label,
        confidence=confidence,
        evidence=tuple(hits[:5]),
        modules=biz.modules,
        focus=biz.focus,
        avoid=biz.avoid,
        finish_hint=biz.finish_hint,
    )


def render_business_block(profile: BusinessProfile | None) -> str:
    """渲染给 worker 的短上下文块；无画像返回空串。"""
    if not profile:
        return ""
    return profile.render()
