"""业务上下文画像：把目标从"有 API/有后台"升级为"这是教务/后勤/支付/审批系统"。

背景：通用工具挖的洞（swagger/弱口令/JS secret/未授权接口）已被同类工具提交殆尽，
先到先得、后到全重复。业务逻辑漏洞（越权/状态机/并发/审批流/金额篡改）需要先理解
业务才能挖，是通用扫描器挖不到的差异化来源。

本模块用编排层已有的静态信息（标题/归属/来源/URL）做初步业务识别，产出短上下文块
注入 Worker prompt，引导 Worker 按业务类型执行针对性的业务逻辑测试；Worker 侦察后
以实际页面为准修正。

资料基线：教育/政企常见业务系统的公开功能语义 + OWASP API Top 10（对象级/功能级
授权、业务逻辑缺陷）。
"""
from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class BusinessProfile:
    biz_id: str
    label: str
    confidence: float
    evidence: tuple[str, ...]
    modules: tuple[str, ...]
    focus: tuple[str, ...]
    avoid: tuple[str, ...] = ()
    finish_hint: str = ""

    def as_dict(self) -> dict:
        return {
            "biz_id": self.biz_id,
            "label": self.label,
            "confidence": round(self.confidence, 2),
            "evidence": list(self.evidence),
            "modules": list(self.modules),
            "focus": list(self.focus),
            "avoid": list(self.avoid),
            "finish_hint": self.finish_hint,
        }

    def render(self) -> str:
        lines = ["# 业务画像（按站点标题/归属/来源推断，需你侦察核实）"]
        lines.append(f"- 疑似业务：{self.label}（confidence={self.confidence:.2f}）")
        if self.modules:
            lines.append("- 典型功能模块：" + "、".join(self.modules))
        lines.append("- 优先按业务逻辑测：")
        for item in self.focus[:6]:
            lines.append(f"  - {item}")
        if self.avoid:
            lines.append("- 避免：")
            for item in self.avoid[:3]:
                lines.append(f"  - {item}")
        if self.finish_hint:
            lines.append(f"- 快速收敛：{self.finish_hint}")
        lines.append("若侦察发现实际业务与推断不符，以实际页面为准，按真实业务调整测试重点。")
        return "\n".join(lines) + "\n\n"


